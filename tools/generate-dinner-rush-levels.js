#!/usr/bin/env node
"use strict";
/*
 * Generates the level campaign for the repo root from real recipes.
 *
 * Source: tools/curated-recipes.json, itself produced by
 * tools/curate-recipes.js from Fannie Farmer's "The Boston Cooking-School
 * Cook Book" (1896, public domain, Project Gutenberg #65061). Every
 * ingredient and every instruction step a player sees is the real book's
 * real text -- nothing here is invented.
 *
 * Each level = one recipe, played in two phases:
 *   Pantry: find the recipe's real ingredients in a grid salted with
 *           decoy ingredients pulled from other recipes.
 *   Stations: the recipe's real instruction steps, shuffled -- drag each
 *             one to the kitchen station (Counter / Stovetop / Oven) its
 *             real verbs say it actually happens at.
 *
 * The level count is NOT fixed -- every curated recipe becomes a level,
 * ordered by difficulty (ingredient count + step count) so the campaign
 * ramps smoothly from simplest to most involved. Add more source
 * cookbooks/cuisines to curated-recipes.json later and the campaign
 * just grows; nothing here needs to change.
 *
 * Usage: node tools/generate-dinner-rush-levels.js > levels-data.js
 */

const fs = require("fs");
const path = require("path");

const CURATED = JSON.parse(fs.readFileSync(path.join(__dirname, "curated-recipes.json"), "utf8"));

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle(arr, rng) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function difficultyScore(r) {
  return r.ingredients.length + r.steps.length;
}

// Use every curated recipe, ordered by difficulty -- the campaign's
// length isn't fixed. Add more source cookbooks/cuisines to
// curated-recipes.json later and the level count just grows with it.
const chosen = CURATED.slice().sort((a, b) => difficultyScore(a) - difficultyScore(b));
const N = chosen.length;

// Global ingredient pool for decoys (deduplicated, case-insensitive).
const allIngredients = [];
const seenIngredient = new Set();
for (const r of CURATED) {
  for (const ing of r.ingredients) {
    const key = ing.toLowerCase();
    if (!seenIngredient.has(key)) {
      seenIngredient.add(key);
      allIngredients.push(ing);
    }
  }
}

function decoyCountFor(levelNumber) {
  const t = (levelNumber - 1) / (N - 1); // 0..1
  return Math.round(2 + t * 6); // 2 decoys at level 1 -> 8 at level 100
}

function pickDecoys(rng, recipe, count) {
  const ownLower = new Set(recipe.ingredients.map((i) => i.toLowerCase()));
  const pool = shuffle(allIngredients.filter((i) => !ownLower.has(i.toLowerCase())), rng);
  return pool.slice(0, count);
}

const levels = chosen.map((recipe, i) => {
  const n = i + 1;
  const rng = mulberry32(n * 7919 + 13);
  const decoys = pickDecoys(rng, recipe, decoyCountFor(n));
  return {
    id: `stage-${n}`,
    name: `Stage ${n}: ${recipe.name}`,
    recipeName: recipe.name,
    ingredients: recipe.ingredients,
    decoys,
    steps: recipe.steps,
  };
});

process.stdout.write(
  "// AUTO-GENERATED by tools/generate-dinner-rush-levels.js — do not hand-edit.\n" +
  "// Source recipes: tools/curated-recipes.json (from Fannie Farmer's The Boston\n" +
  "// Cooking-School Cook Book, 1896, public domain, Project Gutenberg #65061).\n" +
  "// Regenerate with: node tools/generate-dinner-rush-levels.js > levels-data.js\n" +
  "(function (root) {\n  root.DINNER_RUSH_LEVELS = " + JSON.stringify(levels, null, 2) + ";\n})(typeof self !== \"undefined\" ? self : this);\n"
);
process.stderr.write(`Generated ${levels.length} levels from ${CURATED.length} curated recipes.\n`);
